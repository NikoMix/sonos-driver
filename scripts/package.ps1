<#
.SYNOPSIS
    Build and package a portable sonos-driver release zip for Windows (x86_64-pc-windows-msvc).

.DESCRIPTION
    Produces a self-contained, portable release archive that needs no Rust toolchain on
    the target machine. The zip bundles:

      * sonos-driver.exe       - the release CLI binary
      * sonos-driver-gui.exe   - the system-tray desktop GUI binary
      * README.md          - the project front door
      * CHANGELOG.md       - release notes
      * LICENSE-MIT        - MIT licence text
      * LICENSE-APACHE     - Apache-2.0 licence text
      * sonos-driver.toml  - a fully-commented example config (generated by the
                             freshly built binary's own `config example`, so it can
                             never drift from the code)

    The archive is named:

      sonos-driver-<version>-x86_64-pc-windows-msvc.zip

    where <version> is read from [workspace.package] in the workspace Cargo.toml.

    By default the script runs `cargo build --release -p sonos-driver-cli` first, so it
    must be invoked from a shell where the MSVC build environment is initialised
    (a "Developer PowerShell for VS", or after running vcvars64.bat). Use -SkipBuild to
    package an already-built binary without invoking cargo.

    No extra crate or xtask is required (see docs/adr/0010-portable-release-packaging.md).

.PARAMETER OutputDir
    Directory to write the zip into. Created if it does not exist. Defaults to "dist"
    at the repository root.

.PARAMETER SkipBuild
    Skip `cargo build` and package the existing target\release\sonos-driver.exe. The
    build fails fast if that binary is missing.

.EXAMPLE
    pwsh -File scripts/package.ps1
    Builds --release and writes dist\sonos-driver-0.1.0-x86_64-pc-windows-msvc.zip.

.EXAMPLE
    pwsh -File scripts/package.ps1 -SkipBuild -OutputDir C:\releases
    Packages the already-built binary into C:\releases without rebuilding.

.NOTES
    Windows / PowerShell 5.1+ or PowerShell 7+. Uses only built-in cmdlets
    (Compress-Archive); no third-party dependencies.
#>
[CmdletBinding()]
param(
    [string] $OutputDir,
    [switch] $SkipBuild
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

# --- Resolve paths -----------------------------------------------------------
$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$repoRoot  = Resolve-Path (Join-Path $scriptDir '..')
$target    = 'x86_64-pc-windows-msvc'

if (-not $OutputDir) {
    $OutputDir = Join-Path $repoRoot 'dist'
}

$cargoToml = Join-Path $repoRoot 'Cargo.toml'
if (-not (Test-Path $cargoToml)) {
    throw "Cannot find workspace Cargo.toml at '$cargoToml'."
}

# --- Read the workspace version ---------------------------------------------
# Match `version = "x.y.z"` inside the [workspace.package] section only.
$tomlText = Get-Content $cargoToml -Raw
$wpMatch = [regex]::Match(
    $tomlText,
    '(?ms)^\[workspace\.package\]\s*(.*?)(^\[|\z)')
if (-not $wpMatch.Success) {
    throw "Could not locate a [workspace.package] section in $cargoToml."
}
$verMatch = [regex]::Match($wpMatch.Groups[1].Value, '(?m)^\s*version\s*=\s*"([^"]+)"')
if (-not $verMatch.Success) {
    throw "Could not read 'version' from [workspace.package] in $cargoToml."
}
$version = $verMatch.Groups[1].Value
Write-Host "sonos-driver version: $version" -ForegroundColor Cyan

# --- Build (unless skipped) --------------------------------------------------
$cliExe = Join-Path $repoRoot 'target\release\sonos-driver.exe'
$guiExe = Join-Path $repoRoot 'target\release\sonos-driver-gui.exe'
$binaries = @($cliExe, $guiExe)

if ($SkipBuild) {
    Write-Host 'Skipping build (-SkipBuild).' -ForegroundColor Yellow
    foreach ($exe in $binaries) {
        if (-not (Test-Path $exe)) {
            throw "-SkipBuild was set but '$exe' does not exist. Build it first."
        }
    }
} else {
    Write-Host 'Building release binaries: cargo build --release -p sonos-driver-cli -p sonos-driver-gui' -ForegroundColor Cyan
    Push-Location $repoRoot
    try {
        & cargo build --release -p sonos-driver-cli -p sonos-driver-gui
        if ($LASTEXITCODE -ne 0) {
            throw "cargo build failed with exit code $LASTEXITCODE. " +
                  'Ensure the MSVC environment is initialised (see README "Building").'
        }
    } finally {
        Pop-Location
    }
    foreach ($exe in $binaries) {
        if (-not (Test-Path $exe)) {
            throw "Build reported success but '$exe' is missing."
        }
    }
}

# --- Required companion files ------------------------------------------------
$files = @(
    @{ Src = (Join-Path $repoRoot 'README.md');     Name = 'README.md' }
    @{ Src = (Join-Path $repoRoot 'CHANGELOG.md');   Name = 'CHANGELOG.md' }
    @{ Src = (Join-Path $repoRoot 'LICENSE-MIT');    Name = 'LICENSE-MIT' }
    @{ Src = (Join-Path $repoRoot 'LICENSE-APACHE'); Name = 'LICENSE-APACHE' }
)
foreach ($f in $files) {
    if (-not (Test-Path $f.Src)) {
        throw "Required file missing: $($f.Src)"
    }
}

# --- Stage the payload -------------------------------------------------------
$stageRoot = Join-Path ([System.IO.Path]::GetTempPath()) ("sonos-driver-pkg-" + [guid]::NewGuid().ToString('N'))
$stageName = "sonos-driver-$version-$target"
$stageDir  = Join-Path $stageRoot $stageName
New-Item -ItemType Directory -Path $stageDir -Force | Out-Null

try {
    Copy-Item $cliExe (Join-Path $stageDir 'sonos-driver.exe')
    Copy-Item $guiExe (Join-Path $stageDir 'sonos-driver-gui.exe')
    foreach ($f in $files) {
        Copy-Item $f.Src (Join-Path $stageDir $f.Name)
    }

    # Generate the example config from the binary itself so it can never drift.
    $exampleDest = Join-Path $stageDir 'sonos-driver.toml'
    Write-Host 'Generating example config via `sonos-driver config example`' -ForegroundColor Cyan
    $exampleToml = & $cliExe config example 2>$null
    if ($LASTEXITCODE -eq 0 -and $exampleToml) {
        $text = ($exampleToml -join "`r`n") + "`r`n"
        [System.IO.File]::WriteAllText($exampleDest, $text, (New-Object System.Text.UTF8Encoding($false)))
    } else {
        Write-Warning 'Could not generate config from the binary; writing a minimal fallback example.'
        @'
[pipeline]
target-sample-rate = 44100
buffer-ms = 80

[stream]
profile = "l16-pcm"
bind-address = "0.0.0.0"
port = 8080

[sonos]
# room = "Living Room"
discovery-timeout-secs = 3
'@ | Set-Content -Path $exampleDest -Encoding UTF8
    }

    # --- Zip it --------------------------------------------------------------
    if (-not (Test-Path $OutputDir)) {
        New-Item -ItemType Directory -Path $OutputDir -Force | Out-Null
    }
    $zipName = "$stageName.zip"
    $zipPath = Join-Path $OutputDir $zipName
    if (Test-Path $zipPath) {
        Remove-Item $zipPath -Force
    }

    Write-Host "Creating archive: $zipPath" -ForegroundColor Cyan
    # Archive the named folder so the zip contains a single top-level directory.
    Compress-Archive -Path $stageDir -DestinationPath $zipPath -CompressionLevel Optimal

    $sizeKb = [math]::Round((Get-Item $zipPath).Length / 1KB, 1)
    Write-Host ""
    Write-Host "Packaged sonos-driver $version" -ForegroundColor Green
    Write-Host "  -> $zipPath ($sizeKb KB)" -ForegroundColor Green
    Write-Output $zipPath
} finally {
    if (Test-Path $stageRoot) {
        Remove-Item $stageRoot -Recurse -Force -ErrorAction SilentlyContinue
    }
}
